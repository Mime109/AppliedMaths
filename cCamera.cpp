#include "cCamera.h"


/////////////////////////////////////////////////////////////////////////////////////
// constructor
/////////////////////////////////////////////////////////////////////////////////////
cCamera::cCamera()
{
	// init the camera's starting parameters
	projectionMatrix = glm::perspective(glm::radians(m_fov), (float)800.0f / (float)600.0f, m_near, m_far);	
	m_pos   = vec3(0.0f, 0.0f, 7.5f);
	m_vel = vec3(0.0f);
}

/////////////////////////////////////////////////////////////////////////////////////
// destructor
/////////////////////////////////////////////////////////////////////////////////////
cCamera::~cCamera()
{
}

/////////////////////////////////////////////////////////////////////////////////////
// init() - 
/////////////////////////////////////////////////////////////////////////////////////
void cCamera::init()
{
	// init the projection matrix - i.e. what the camera can see
	projectionMatrix = glm::perspective(glm::radians(m_fov), (float)800.0f / (float)600.0f, m_near, m_far);
}


/////////////////////////////////////////////////////////////////////////////////////
// update() - create the camera view matrix
/////////////////////////////////////////////////////////////////////////////////////
void cCamera::update()
{	
	mat4 t	= glm::translate(mat4(1.0f), vec3(-m_pos));
	viewMatrix = t;
}